namespace Theme
{
	int Count() { return kPaletteCount; }

	const wchar_t* Name(int index)
	{
		return (index >= 0 && index < kPaletteCount) ? kPalettes[index].name : L"";
	}

	int Find(const CString& name)
	{
		for (int i = 0; i < kPaletteCount; ++i)
			if (name.CompareNoCase(kPalettes[i].name) == 0)
				return i;
		return -1;
	}

	int Current() { return g_current; }

	void Apply(int index)
	{
		if (index < 0 || index >= kPaletteCount)
			index = 0;
		g_current = index;
		for (int i = 0; i < TC_COUNT; ++i)
			g_themeColors[i] = kPalettes[index].c[i];
	}

	void LoadFromSettings()
	{
		const CString name = AfxGetApp() ? AfxGetApp()->GetProfileString(L"Settings", L"Theme", L"Stash") : CString(L"Stash");
		Apply(Find(name));
	}

	void SaveToSettings(int index)
	{
		if (AfxGetApp() && index >= 0 && index < kPaletteCount)
			AfxGetApp()->WriteProfileString(L"Settings", L"Theme", kPalettes[index].name);
	}
}
